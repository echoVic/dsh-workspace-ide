#!/usr/bin/env node
/**
 * Bundle the Client half of dsh-workspace-ide.
 *
 * The DSH browser runtime boots a client package by executing one plain script
 * that calls `window.__ModuleLoader__.load({ id, factory })`. There is no
 * bundler in the profile and the only module the factory may require is
 * `react`. Sources live in `src/client/` — plain `.js` fragments and
 * TypeScript `.ts`/`.tsx` fragments; the TS ones are compiled by `tsc` (no
 * bundler) into `build/client-parts/` and then every part is concatenated (in
 * the fixed order below) into the single shipped file `lib/client.js`. Every
 * source file is a fragment of the same factory body and may only attach to the
 * shared `S` object — no import/export, no top-level `return`.
 *
 * The TypeScript compiler is the only authored-toolchain dependency: it emits
 * plain ES2022 scripts, so the artifact keeps its contract (one
 * `__ModuleLoader__.load` call, `require('react')` only, no bundler).
 *
 * Usage:
 *   node scripts/build-client.mjs            write lib/client.js
 *   node scripts/build-client.mjs --check    compare only; exit 1 when stale
 */

import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PROJECT = path.resolve(HERE, '..');
const SRC_DIR = path.join(PROJECT, 'src', 'client');
const OUT_FILE = path.join(PROJECT, 'lib', 'client.js');
const TSC_BIN = path.join(PROJECT, 'node_modules', 'typescript', 'bin', 'tsc');
const TSC_PROJECT = path.join(PROJECT, 'tsconfig.client-build.json');
const BUILD_DIR = path.join(PROJECT, 'build', 'client-parts');

/** Concatenation order; the names are part of the file contract. */
const SOURCES = [
  '00-core.ts',
  '05-icons.ts',
  '07-highlight.ts',
  '08-markdown.ts',
  '10-shell.ts',
  '20-files.ts',
  '30-search.ts',
  '40-git.ts',
  '99-face.ts',
];

const HEADER = `/* generated by scripts/build-client.mjs — do not edit */
window.__ModuleLoader__.load({
  id: 'dsh-workspace-ide',
  factory(require) {
    const React = require('react');
    const h = React.createElement;
    const { useCallback, useEffect, useMemo, useRef, useState } = React;
    const S = {};
`;

const FOOTER = `
    return S.face;
  },
});
`;

const IMPORT_STATEMENT = /^[ \t]*(?:import|export)[ \t{*]/m;
const ANY_REQUIRE = /\brequire[ \t]*\([ \t]*(["'])([^"']+)\1[ \t]*\)/g;
const FORBIDDEN_RESOLVE = /@deepseek-ai\//;

/**
 * Reject a source fragment that would break the module-face constraints before
 * it reaches the artifact (the smoke test re-checks the built file as well).
 *
 * @param {string} file - source basename, for the message.
 * @param {string} text - source text.
 * @returns {string[]} human-readable problems (empty when the fragment is fine).
 */
function inspectSource(file, text) {
  const problems = [];
  if (IMPORT_STATEMENT.test(text)) {
    problems.push(`${file}: contains an import/export statement; the factory bundle must be plain script`);
  }
  for (const match of text.matchAll(ANY_REQUIRE)) {
    if (match[2] !== 'react') {
      problems.push(`${file}: requires "${match[2]}"; "react" is the only module a client half may require`);
    }
  }
  if (FORBIDDEN_RESOLVE.test(text)) {
    problems.push(`${file}: references a @deepseek-ai/ package; only "react" may be required`);
  }
  return problems;
}

/**
 * Compile the TypeScript fragments (if any) into `build/client-parts/`.
 * @returns {{ ok: boolean, message: string }} compilation result.
 */
function compileTypeScript() {
  const hasTypeScript = SOURCES.some((file) => /\.(ts|tsx)$/.test(file));
  if (!hasTypeScript) return { ok: true, message: '' };
  if (!existsSync(TSC_BIN)) {
    return { ok: false, message: `TypeScript compiler missing (${TSC_BIN}); run "npm ci"` };
  }
  const result = spawnSync(process.execPath, [TSC_BIN, '-p', TSC_PROJECT], { encoding: 'utf8' });
  if (result.status === 0) return { ok: true, message: '' };
  const detail = String(result.stdout || '') + String(result.stderr || '');
  return { ok: false, message: detail.trim() || 'tsc failed' };
}

/** Resolve one source part: TypeScript fragments come from the compiled dir. */
function resolvePart(file) {
  if (/\.(ts|tsx)$/.test(file)) {
    return path.join(BUILD_DIR, file.replace(/\.(ts|tsx)$/, '.js'));
  }
  return path.join(SRC_DIR, file);
}

/**
 * Compose the artifact text from the current sources.
 * @returns {Promise<string>} artifact bytes as text.
 */
async function compose() {
  const chunks = [HEADER];
  for (const file of SOURCES) {
    const absolute = resolvePart(file);
    let text;
    try {
      text = await readFile(absolute, 'utf8');
    } catch (cause) {
      throw new Error(`missing client source ${file} (${absolute}): ${String(/** @type {any} */ (cause).message)}`);
    }
    const problems = inspectSource(file, text);
    if (problems.length > 0) {
      throw new Error(`invalid client source:\n  - ${problems.join('\n  - ')}`);
    }
    const normalized = text.replace(/\s+$/, '');
    chunks.push(`\n/* ─── src/client/${file} ${'─'.repeat(Math.max(3, 62 - file.length))} */\n${normalized}\n`);
  }
  chunks.push(FOOTER);
  return chunks.join('');
}

async function readArtifact() {
  try {
    return await readFile(OUT_FILE, 'utf8');
  } catch (cause) {
    if (/** @type {any} */ (cause).code === 'ENOENT') return null;
    throw cause;
  }
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const unknown = args.filter((argument) => argument !== '--check');
  if (unknown.length > 0) {
    process.stderr.write(`build-client: unknown argument(s): ${unknown.join(', ')}\nusage: node scripts/build-client.mjs [--check]\n`);
    process.exit(2);
  }

  const compiled = compileTypeScript();
  if (!compiled.ok) {
    process.stderr.write(`build-client: TypeScript compilation failed:\n${compiled.message}\n`);
    process.exit(1);
  }

  let artifact;
  try {
    artifact = await compose();
  } catch (cause) {
    process.stderr.write(`build-client: ${String(/** @type {any} */ (cause).message)}\n`);
    process.exit(1);
  }

  const current = await readArtifact();
  if (check) {
    if (current === artifact) {
      process.stdout.write(`build-client: lib/client.js is up to date (${Buffer.byteLength(artifact, 'utf8')} bytes)\n`);
      return;
    }
    const reason = current === null ? 'lib/client.js is missing' : 'lib/client.js is stale';
    process.stderr.write(`build-client: ${reason}; run "node scripts/build-client.mjs" to regenerate it\n`);
    process.exit(1);
  }
  if (current === artifact) {
    process.stdout.write(`build-client: lib/client.js unchanged (${Buffer.byteLength(artifact, 'utf8')} bytes)\n`);
    return;
  }
  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, artifact, 'utf8');
  process.stdout.write(`build-client: wrote lib/client.js (${Buffer.byteLength(artifact, 'utf8')} bytes from ${SOURCES.length} sources)\n`);
}

await main();
